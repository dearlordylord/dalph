#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = import.meta.dirname
const manifestPath = join(root, "journal-events.json")
const modulePath = join(root, "fastcheck", "journal-events.generated.mjs")
const mappingPath = join(root, "JOURNAL-EVENT-MAPPING.generated.md")
const leanPath = join(root, "lean", "JournalEvents.generated.lean")
const agdaPath = join(root, "agda", "JournalEventsGenerated.agda")
const dafnyPath = join(root, "dafny", "JournalEvents.generated.dfy")
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"))

if (manifest.length !== 23) throw new Error(`expected 23 journal events, found ${manifest.length}`)
const names = new Set()
for (const event of manifest) {
  if (!/^[A-Z][A-Za-z]+$/.test(event.name)) throw new Error(`invalid event name ${event.name}`)
  if (!new Set(["action", "occurrence"]).has(event.kind)) throw new Error(`invalid kind for ${event.name}`)
  if (names.has(event.name)) throw new Error(`duplicate event ${event.name}`)
  if (new Set(event.fields).size !== event.fields.length) throw new Error(`duplicate field in ${event.name}`)
  names.add(event.name)
}

const lowerFirst = (value) => value[0].toLowerCase() + value.slice(1)
const generatedModule = `// Generated by ../generate-journal-events.mjs; do not edit.\n` +
  `export const EVENT_MANIFEST = ${JSON.stringify(manifest, null, 2)}\n`
const rows = manifest.map((event) =>
  `| \`${event.name}\` | ${event.kind} | \`${event.fields.join(", ")}\` | \`${lowerFirst(event.name)}\` | \`${lowerFirst(event.name)}\` | \`${event.name}\` |`
).join("\n")
const generatedMapping = `<!-- Generated by generate-journal-events.mjs; do not edit. -->
# Generated journal event mapping

This table is derived from \`journal-events.json\`. The parity checker verifies
that every mapped constructor occurs in each prover's exhaustive event consumer.

| JavaScript tag | Kind | Ordered payload | Lean | Agda | Dafny |
|---|---|---|---|---|---|
${rows}
`

const isAction = (event) => event.kind === "action"
const leanValue = (event, field) => {
  if (["subjects", "facts"].includes(field)) return "[]"
  if (field === "complete") return "true"
  if (field === "direction") return ".pause"
  if (field === "reason") return event.name === "ClaimedTaskIneligible" ? ".notOpen" : ".staleTargetHead"
  if (field === "outcome") return ".created"
  if (field === "report") return ".running"
  return "0"
}
const agdaValue = (event, field) => {
  if (["subjects", "facts"].includes(field)) return "[]"
  if (field === "complete") return "true"
  if (field === "task") return "a"
  if (field === "direction") return "pause"
  if (field === "reason") return event.name === "ClaimedTaskIneligible" ? "notOpen" : "staleTargetHead"
  if (field === "outcome") return "created"
  if (field === "report") return "running"
  return "0"
}
const dafnyValue = (event, field) => {
  if (["subjects", "facts"].includes(field)) return "[]"
  if (field === "complete") return "true"
  if (field === "task") return "A"
  if (field === "direction") return "Pause"
  if (field === "reason") return event.name === "ClaimedTaskIneligible" ? "NotOpen" : "StaleTargetHead"
  if (field === "outcome") return "Created"
  if (field === "report") return "Running"
  return "0"
}
const call = (name, fields, value) => `${name}(${fields.map(value).join(", ")})`
const leanEvents = manifest.map((event) =>
  `  .${lowerFirst(event.name)} ${event.fields.map((field) => leanValue(event, field)).join(" ")}`
).join(",\n")
const agdaEvents = manifest.map((event) => {
  const constructor = `${lowerFirst(event.name)} ${event.fields.map((field) => agdaValue(event, field)).join(" ")}`
  return `  ${isAction(event) ? "act" : "occ"} (${constructor})`
}).join(" ::\n")
const dafnyEvents = manifest.map((event) => {
  const constructor = call(event.name, event.fields, (field) => dafnyValue(event, field))
  return `    ${isAction(event) ? "Act" : "Occ"}(${constructor})`
}).join(",\n")
const generatedLean = `-- Generated by ../generate-journal-events.mjs; do not edit.\nimport Journal\nopen Journal\n\ndef eventWitnesses : List Event := [\n${leanEvents}\n]\n\nexample : eventWitnesses.length = 23 := by decide\n`
const generatedAgda = `-- Generated by ../generate-journal-events.mjs; do not edit.\nmodule JournalEventsGenerated where\n\nopen import Journal\n\nevent-witnesses : List Event\nevent-witnesses =\n${agdaEvents} ::\n  []\n`
const generatedDafny = `// Generated by ../generate-journal-events.mjs; do not edit.\ninclude "Journal.dfy"\n\nfunction EventWitnesses(): seq<Event>\n{\n  [\n${dafnyEvents}\n  ]\n}\n\nlemma EventWitnessCount()\n  ensures |EventWitnesses()| == 23\n{}\n`

const outputs = [
  [modulePath, generatedModule], [mappingPath, generatedMapping],
  [leanPath, generatedLean], [agdaPath, generatedAgda], [dafnyPath, generatedDafny]
]
if (process.argv.includes("--check")) {
  for (const [path, expected] of outputs) {
    if (readFileSync(path, "utf8") !== expected) throw new Error(`${path} is stale; run generate-journal-events.mjs`)
  }
} else {
  for (const [path, contents] of outputs) writeFileSync(path, contents)
}
