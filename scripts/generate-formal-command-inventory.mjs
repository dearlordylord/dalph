import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { quintGateCommandManifest } from "./quint-gate-command-manifest.mjs"
import { quintHostedModelFamilies, quintHostedShardCount } from "./quint-hosted-shards.mjs"

const outputPath = fileURLToPath(
  new URL("../packages/dalph/src/qualification/formal-command-inventory.generated.ts", import.meta.url)
)

export const renderFormalCommandInventory = (commands, families, shardCount) => {
  /** @type {Array<number | undefined>} */
  const assignment = Array.from({ length: commands.length }, () => undefined)
  for (const { first, last, shard } of families) {
    if (
      !Number.isInteger(first) ||
      !Number.isInteger(last) ||
      first > last ||
      !Number.isInteger(shard) ||
      shard < 0 ||
      shard >= shardCount
    ) {
      throw new Error("Hosted Quint family has an invalid range or shard")
    }
    for (let position = first; position <= last; position += 1) {
      if (position >= commands.length || assignment[position] !== undefined)
        throw new Error(`Hosted Quint position ${position} is duplicated or outside the command manifest`)
      assignment[position] = shard
    }
  }
  if (assignment.some((shard) => shard === undefined))
    throw new Error("Hosted Quint families do not cover every command manifest position")
  if (commands.length === 0) throw new Error("Quint command manifest is empty")
  return [
    "/** Generated by scripts/generate-formal-command-inventory.mjs from the executable Quint manifest and hosted shard families. */",
    `export const formalCommandCount = ${commands.length}`,
    "/** Character at each command position names its hosted shard. */",
    "export const formalShardByPosition =",
    `  "${assignment.join("")}"`,
    ""
  ].join("\n")
}

export const expectedFormalCommandInventory = () =>
  renderFormalCommandInventory(quintGateCommandManifest, quintHostedModelFamilies, quintHostedShardCount)

export const checkFormalCommandInventory = async () => {
  const current = await readFile(outputPath, "utf8")
  if (current !== expectedFormalCommandInventory())
    throw new Error(
      "Generated formal command inventory is stale; run node scripts/generate-formal-command-inventory.mjs --write"
    )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 3 || !["--check", "--write"].includes(process.argv[2]))
    throw new Error("Usage: node scripts/generate-formal-command-inventory.mjs --check|--write")
  if (process.argv[2] === "--write") await writeFile(outputPath, expectedFormalCommandInventory())
  else await checkFormalCommandInventory()
}
